class Macros:
    def __init__(self):
        self.rows = []

    def add(self, key: str, value, prov: str, fmt: str = "{:.3f}"):
        txt = value if isinstance(value, str) else (fmt.format(value) if value is not None else "n/a")
        self.rows.append((key, txt, prov))
        return txt

    def write(self, d: Path):
        lines = ["% AUTO-GENERATED by phishresearch.reporting - do not edit",
                 "\\makeatletter", "\\newcommand{\\res}[1]{\\@ifundefined{r@#1}{\\textbf{??#1??}}{\\@nameuse{r@#1}}}"]
        for k, v, _ in self.rows:
            lines.append(f"\\@namedef{{r@{k}}}{{{v}}}")
        lines.append("\\makeatother")
        (d / "macros.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
        pd.DataFrame(self.rows, columns=["key", "value", "provenance"]).to_csv(d / "provenance.csv", index=False)


def _pct(x):
    return f"{100 * x:.1f}"


def _f(x, n=3):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{n}f}"


def _signed(x, n=3):
    return f"{x:+.{n}f}"


def _style(plt):
    plt.rcParams.update({"font.family": "serif", "font.size": 7, "axes.edgecolor": INK2, "axes.labelcolor": INK,
                         "xtick.color": INK2, "ytick.color": INK2, "axes.spines.top": False, "axes.spines.right": False,
                         "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.5, "axes.axisbelow": True,
                         "figure.facecolor": "white", "axes.facecolor": "white", "legend.frameon": False,
                         "pdf.fonttype": 42})


